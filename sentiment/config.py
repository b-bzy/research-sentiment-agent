"""全局常量与版本号。

设计要点（对应架构方案第五、六节）：
- SCORE_VERSION / CALC_VERSION 双版本号分开管理：
  打分口径（贵、慢、只追加）与聚合口径（便宜、快、可反复重算）解耦，
  改聚合口径时不必重跑打分。
- 所有路径基于 ``__file__`` 推导，不硬编码绝对路径，换机器直接能跑。
"""

from pathlib import Path

# ---------------------------------------------------------------- 版本号

#: 打分口径版本号，写进 score.model_version；规则表一变就要升版
SCORE_VERSION = 'rule-v1'

#: 聚合口径版本号，写进 daily_index.calc_version；净得分公式一变就要升版
CALC_VERSION = 'netscore-v1'

# ---------------------------------------------------------------- 路径

#: 项目根目录（本文件在 sentiment/config.py，故上溯两级）
BASE_DIR = Path(__file__).resolve().parent.parent

#: 数据目录
DATA_DIR = BASE_DIR / 'data'

#: 样本研报投递目录（demo 用 .txt 代替 PDF，避开第三方解析库）
INBOX_DIR = DATA_DIR / 'inbox'

#: HTML 看板输出目录
OUT_DIR = BASE_DIR / 'out'

#: SQLite 库文件
DB_PATH = DATA_DIR / 'sentiment.db'

# ---------------------------------------------------------------- 阈值

#: 大盘情绪分（0-100）高于它算「偏多」
MARKET_BULL_THRESHOLD = 60

#: 大盘情绪分（0-100）低于它算「偏空」
MARKET_BEAR_THRESHOLD = 40

#: 单日变化超过它就加重提醒。
#: 天天喊「今天偏多」两周就会被交易员静音，只在显著变化时加重才有人看。
ALERT_DELTA = 15

#: 多空计数口径：direction > 该值记看多
BULL_CUTOFF = 0.25

#: 多空计数口径：direction < 该值记看空
BEAR_CUTOFF = -0.25

#: 置信度低于它的打分进人工复核队列（demo 里仅在看板上标注）
LOW_CONFIDENCE = 0.6

# ---------------------------------------------------------------- 负面非对称加权

#: ★ 负面非对称加权系数（架构方案第五节的显式设计项，落地在**聚合层**）。
#:
#: 坑本身：调研文档 01 第三节说得很清楚——分析师不轻易喊空，
#: 正负等权会让指标长期漂在偏多区而失去区分度。本样本集实测也确实如此：
#: 多头票是空头票的 1.7 倍，净得分长期落在 +21 附近。
#:
#: 这个坑分两半，本项目的处理方式是**语义那一半做在打分层，加权那一半做在聚合层**：
#:   - 语义半边（已落地）：score.SPECIAL_RULES 专门吃「暂不看空 / 谨慎追空 /
#:     前多保护利润」这类**变相偏多**的表达，不让它们被字面上的「空」字骗成看空。
#:     这一半必须在打分层做，因为它是「判准方向」，不是「调口径」。
#:   - 加权半边（本常量）：把空头票乘一个 > 1 的系数再算净得分。
#:     它必须在聚合层做，因为它是个**会反复调参**的口径——放在打分层的话，
#:     每调一次权重就要重跑一遍全量打分（生产版这一步要花 LLM 的钱）。
#:
#: ★ demo 版故意保持 1.0（完全等权），原因不是没实现，而是**顺序问题**：
#:   架构方案第六节要求「先把 IndexMundi 净得分 baseline 这条最笨的路径跑通，
#:   之后任何复杂加权都要证明能跑赢它」。demo 只有 3 天、24 篇虚构样本，
#:   没有任何可以用来定标 BEAR_WEIGHT 的历史数据——凭空拍一个 1.3 上去，
#:   得到的只是一个更好看但无法验证的数字。
#:   生产版的做法：改这个值 + 升 CALC_VERSION，两套口径的曲线并排放在看板上比。
#:   打分一行都不用重跑，这正是「打分与聚合彻底分离」换来的东西。
BEAR_WEIGHT = 1.0
